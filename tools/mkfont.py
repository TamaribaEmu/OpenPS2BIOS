def main(out):
    lines = ["/* SPDX-License-Identifier: MIT */",
             "/* Generated by tools/mkfont.py: 5x7 glyphs for ASCII 32..126, one byte per",
             "   row, bit 4 = leftmost column. */",
             "static const unsigned char font5x7[95][7] = {"]
    for code in range(32, 127):
        rows = G[chr(code)].split('|')
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(code)
        vals = [sum(1 << (4 - i) for i, c in enumerate(r) if c == '#') for r in rows]
        lines.append("    {%s}, /* %r */" % (", ".join("0x%02x" % v for v in vals), chr(code)))
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(sys.argv[1])
